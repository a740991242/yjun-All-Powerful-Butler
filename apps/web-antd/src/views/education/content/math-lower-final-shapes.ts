function task(
  suffix: string,
  prompt: string,
  rule: Question['rule'],
  explanation: string,
  labels?: string[],
  visual?: Visual,
): Question {
  return {
    id: `${id}-${suffix}`,
    knowledge: id,
    prompt,
    rule,
    explanation,
    visual,
    hint: '先明确数原图块还是整体；每个带字母块只数一次，字母和外框不计。内部拼缝不是整体外边。',
    choices: labels?.map((label) => ({ id: label, label })),
  };
}
function fields(
  suffix: string,
  prompt: string,
  values: number[],
  explanation: string,
  visual?: Visual,
) {
  return task(
    suffix,
    prompt,
    { kind: 'steps', values },
    explanation,
    undefined,
    visual,
  );
}
function manual(suffix: string, prompt: string, visual?: Visual) {
  return task(
    suffix,
    prompt,
    { kind: 'manual' },
    '指定实际活动完整做过并解释才确认。没有材料、只看网页或部分完成请跳过，范围和计划另如实记录。',
    undefined,
    visual,
  );
}
