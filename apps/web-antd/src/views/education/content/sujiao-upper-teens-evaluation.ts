const id = 'sj-upper-teens-evaluation';
function tasks(review: boolean): Question[] {
  const q = (
    key: string,
    prompt: string,
    rule: Question['rule'],
    explanation: string,
  ): Question => ({
    id: `${id}-${review ? 'r' : 'q'}-${key}`,
    knowledge: `${id}-${key}`,
    prompt,
    rule,
    hint: '本项单独看真实证据，数量/十与一/标记颗数分清；反思不自动判对错。',
    explanation,
  });
  return [
    {
      ...q(
        'composition',
        review
          ? '数字18，先填有几个单个一，再填有几个十。'
          : '数字16，先填有几个十，再填有几个单个一。',
        { kind: 'steps', values: review ? [8, 1] : [1, 6] },
        '十位都是1个十；单个一和所有一不能混，复习填写顺序也改变。',
      ),
      visual: { kind: 'digit-counter', tens: 1, ones: review ? 8 : 6 },
    },
    q(
      'all-ones',
      review
        ? '18件物品若全部逐件算，每件算一个一，共有几个一？不是只问个位。'
        : '16件物品若全部逐件算，每件算一个一，共有几个一？不是只问个位。',
      { kind: 'number', value: review ? 18 : 16 },
      '全部16/18个一与个位6/8个一是不同问题，整理成一十不减少原物数量。',
    ),
    q(
      'add-process',
      review
        ? '12+4，先填原有单个一与新4合并后的单个一数量，再填最后总数。'
        : '13+2，先填原有单个一与新2合并后的单个一数量，再填最后总数。',
      { kind: 'steps', values: review ? [6, 16] : [5, 15] },
      '原十保留，先合并单个一，再和十合起来；网页答案不证明实际拨珠已做。',
    ),
    q(
      'subtract-process',
      review
        ? '18−4，先填取走4后剩几个单个一，再填最后总数。'
        : '15−2，先填取走2后剩几个单个一，再填最后总数。',
      { kind: 'steps', values: review ? [4, 14] : [3, 13] },
      '十保留，只取足够的单个一，本题不退位；减10另须取整十。',
    ),
    q(
      'ten-marker',
      review
        ? '课堂已约定一枚大纸标记代表10件、一枚小纸标记代表1件。1大7小，先填代表几件物品，再填实际有几枚纸标记。'
        : '课堂已约定一枚大纸标记代表10件、一枚小纸标记代表1件。1大4小，先填代表几件物品，再填实际有几枚纸标记。',
      { kind: 'steps', values: review ? [17, 8] : [14, 5] },
      '一大是约定代表十，不是因为尺寸大自动算十；代表物品14/17，与纸标记5/8分清。',
    ),
    {
      ...q(
        'agreement',
        review
          ? '朋友不知道你的一大换十小约定，能要求他直接按大小猜代表多少件吗？'
          : '任意一块大石子自然就等于十块小石子吗？',
        { kind: 'choice', value: 'agreed' },
        '计数表示先说明共同约定，大小本身不能推出单位值；本活动是原创课堂模型，不冒古代原物。',
      ),
      choices: [
        {
          id: 'agreed',
          label: review
            ? '不能，先说明一大代表十的约定'
            : '不是，必须先约定一大代表十',
        },
        {
          id: 'guess',
          label: review ? '能，大就一定十' : '是，尺寸大天然等于十',
        },
      ],
    },
    {
      ...q(
        'independent-evidence',
        review
          ? '认识与组成已做，但计数器操作尚未做，可以把两项都记已完成吗？'
          : '网页计算答对，就自动认为认识、操作、解释三项都满星吗？',
        { kind: 'choice', value: 'separate' },
        '三项分别看实际证据与帮助/困难，允许一项完成另一项待做；网页正确不代替实际，不自动评星。',
      ),
      choices: [
        {
          id: 'separate',
          label: review
            ? '不可以，操作单独记待做'
            : '不能，三项证据和反思各自记录',
        },
        {
          id: 'auto',
          label: review
            ? '可以，用前一项完成代替'
            : '可以，正确率代替全部实际证据',
        },
      ],
    },
  ];
}
