import type { Lesson, Question } from '../learning/types';

const id = 'ml-shopping-practice';
function manual(suffix: string, prompt: string, hint: string): Question {
  return {
    id: `${id}-${suffix}`,
    knowledge: id,
    prompt,
    rule: { kind: 'manual' },
    hint,
    explanation:
      '只记录实际做过的活动；未做可跳过。纸上或家中模拟不是实际消费，确认不等于客观答对。',
  };
}
function reflection(suffix: string, prompt: string): Question {
  return {
    id: `${id}-${suffix}`,
    knowledge: id,
    prompt,
    rule: { kind: 'reflection' },
    hint: '写下实际发生的过程，也可由家长代录；没有做过就说明未做，或者跳过，不编造经历。',
    explanation: '这是过程与感受记录，没有统一正确答案，不计入客观题正确率。',
  };
}
