export function finalCompleteComparisons(review: boolean): Question[] {
  const rows = review
    ? ([
        [6, '+', 8, 14, '-', 0],
        [10, '-', 0, 19, '-', 10],
        [8, '+', 7, 16, '-', 0],
        [10, '-', 7, 4, '-', 0],
        [13, '+', 0, 4, '+', 8],
        [8, '+', 8, 16, '-', 0],
      ] as const)
    : ([
        [6, '+', 7, 13, '-', 0],
        [8, '+', 0, 17, '-', 10],
        [7, '+', 7, 15, '-', 0],
        [10, '-', 6, 6, '-', 0],
        [12, '+', 0, 3, '+', 8],
        [8, '+', 6, 14, '-', 0],
      ] as const);
  return rows.map(([a, op, b, c, rightOp, d], i) => {
    const left = op === '+' ? a + b : a - b;
    const right = rightOp === '+' ? c + d : c - d;
    let relation = '=';
    if (left > right) relation = '>';
    else if (left < right) relation = '<';
    const first = b === 0 ? String(a) : `${a}${op === '-' ? '−' : '+'}${b}`;
    const second =
      d === 0 ? String(c) : `${c}${rightOp === '-' ? '−' : '+'}${d}`;
    return {
      id: `${grid}-${review ? 'r' : 'q'}-complete-compare-${i}`,
      knowledge: `${grid}-calculation`,
      prompt: `比较${first}与${second}，前一边应填哪种关系？`,
      rule: { kind: 'choice', value: relation },
      choices: ['>', '<', '='].map((label) => ({ id: label, label })),
      hint: '先把两边分别算出，再比较；有减法时不能直接比较被减数。',
      explanation: `前一边是${left}，后一边是${right}；${left}${relation}${right}。比较完整结果，不只比较一个加数或被减数。`,
    };
  });
}
export function finalCompletePartitions(review: boolean): Question[] {
  return (review ? [15, 18] : [14, 17]).map((total, i) => ({
    id: `${map}-${review ? 'r' : 'q'}-complete-family-${i}`,
    knowledge: `${map}-calculation`,
    prompt: `本站开放分合：${total}分成两个0～20的整数，可以有0。依次填自己的一种分法；纸面活动再写同一整体的相关加减式。`,
    rule: { kind: 'partition', total, parts: 2, minimum: 0 },
    hint: '两部分的和须等于整体，两空都要填写；0不是没填。每次从同一整体出发。',
    explanation: `0和${total}、1和${total - 1}，直到${total}和0都满足本题，共${total + 1}种。自己选a与b后，纸面分别写a+b=${total}、b+a=${total}、${total}−a=b、${total}−b=a，并逐式核对。网页两空仅判断分法，不能代替四式实做；前面只用正数的题有不同范围。`,
  }));
}
