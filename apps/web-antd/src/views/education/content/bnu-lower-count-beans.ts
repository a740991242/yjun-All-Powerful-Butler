import type { Lesson, Question, Visual } from '../learning/types';
const id = 'bnu-lower-count-beans';
function task(
  suffix: string,
  prompt: string,
  rule: Question['rule'],
  explanation: string,
  values?: number[],
): Question {
  const visual: undefined | Visual = values
    ? { kind: 'place-counters', values }
    : undefined;
  return {
    id: `${id}-${suffix}`,
    knowledge: id,
    prompt,
    rule,
    explanation,
    hint: '先明确数位、所数对象与条件；真实先估后数、拨画珠和读写另记。',
    ...(visual ? { visual } : {}),
  };
}
const steps = (
  suffix: string,
  prompt: string,
  values: number[],
  explanation: string,
  counters?: number[],
) => task(suffix, prompt, { kind: 'steps', values }, explanation, counters);
const number = (
  suffix: string,
  prompt: string,
  value: number,
  explanation: string,
  counters?: number[],
) => task(suffix, prompt, { kind: 'number', value }, explanation, counters);
function choice(
  suffix: string,
  prompt: string,
  value: string,
  labels: string[],
  explanation: string,
): Question {
  return {
    ...task(suffix, prompt, { kind: 'choice', value }, explanation),
    choices: labels.map((label) => ({ id: label, label })),
  };
}
