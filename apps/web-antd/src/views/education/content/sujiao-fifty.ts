const id = 'sj-lower-fifty';
function tasks(review: boolean): Question[] {
  const over = review ? 55 : 53;
  const under = review ? 48 : 46;
  const a = review ? 47 : 48;
  const b = review ? 53 : 52;
  const c = (
    key: string,
    prompt: string,
    choices: Question['choices'],
    value: string,
    explanation: string,
  ): Question => ({
    id: `${id}-${review ? 'r' : 'q'}-${key}`,
    knowledge: `${id}-${key}`,
    prompt,
    choices,
    rule: { kind: 'choice', value },
    hint: '看目标50、实际记录和计数单位，不把估计当准确结论。',
    explanation,
  });
  return [
    c(
      'closest',
      `目标抓50个。甲数清${under}个，乙数清${over}个，谁更接近50？`,
      [
        { id: 'a', label: '甲' },
        { id: 'b', label: '乙' },
        { id: 'same', label: '一样接近' },
      ],
      review ? 'a' : 'b',
      `甲差${50 - under}，乙差${over - 50}，差得较少的更接近，不按实际数量较大判。`,
    ),
    {
      id: `${id}-${review ? 'r' : 'q'}-tie`,
      knowledge: `${id}-tie`,
      prompt: `目标50个，甲数清${a}个，乙数清${b}个。选出所有最接近50的记录。`,
      choices: [
        { id: 'a', label: `甲：${a}个` },
        { id: 'b', label: `乙：${b}个` },
      ],
      rule: { kind: 'set', values: ['a', 'b'] },
      hint: '分别数到50的差距，可能两边同样接近。',
      explanation: `两人都与50差${50 - a}，都应选择，不能只选较大的。`,
    },
    {
      id: `${id}-${review ? 'r' : 'q'}-short`,
      knowledge: `${id}-short`,
      prompt: `目标50个，实际数清${under}个，还少几个？`,
      rule: { kind: 'number', value: 50 - under },
      hint: '从实际数接着数到50。',
      explanation: `少${50 - under}个，目标与实际的差距不等于抓了几把。`,
    },
    {
      id: `${id}-${review ? 'r' : 'q'}-extra`,
      knowledge: `${id}-extra`,
      prompt: `目标50个，实际数清${over}个，多了几个？`,
      rule: { kind: 'number', value: over - 50 },
      hint: '从50数到实际数，比较的是个数。',
      explanation: `多${over - 50}个。`,
    },
    c(
      'hand',
      review
        ? '换成大小不同的另一种材料，还能照搬上次抓的把数吗？'
        : '两个人都想抓50个，他们必须抓同样把数吗？',
      [
        { id: 'check', label: '不能保证，需要看每把数量并实际数清' },
        { id: 'same', label: '必须相同，50永远对应固定把数' },
      ],
      'check',
      '手、物品大小和每把抓法会影响数量，先取一把数清可作参照，不规定50一定几把。',
    ),
    c(
      'stack',
      review
        ? '仍是50个同样积木，改成几摞，整体摆放高度能只凭个数确定吗？'
        : '两组都是50个积木，积木大小或摆法不同，高度一定相同吗？',
      [
        { id: 'no', label: '不一定，需说明积木大小与摆法并观察' },
        { id: 'yes', label: '一定相同，因为都是50个' },
      ],
      'no',
      '数量与高度单位不同，不给出尺寸和摆法不能推算实际高度。',
    ),
    c(
      'water',
      review
        ? '换了杯子或桶，上次倒18杯的记录能直接当新桶装满的杯数吗？'
        : '往桶里已倒18杯，还没有装满，仅凭“18杯”能知道装满恰好要多少杯吗？',
      [
        {
          id: 'observe',
          label: '不能，需要继续操作观察，并保持杯子和每杯量一致',
        },
        { id: 'fifty', label: '能，所有桶都是50杯装满' },
      ],
      'observe',
      '杯和桶的大小会影响结果，不能编造统一装满杯数；部分记录不能当完成记录。',
    ),
    c(
      'space',
      review
        ? '同一块地，改成做操队形后，能否照搬紧挨站立的人数结论？'
        : '想知道50人做操够不够站，只看50这个数就能判断吗？',
      [
        { id: 'layout', label: '不能，需看场地、队形和每人前后左右间隔' },
        { id: 'count', label: '能，50人在哪块空地都站得下' },
      ],
      'layout',
      '总人数一样，活动间隔与场地条件不同仍会影响够不够。实际班级活动由老师组织。',
    ),
    c(
      'unit',
      review
        ? '“50米”和“50页”都含50，它们表示同一种数量吗？'
        : '“50个积木”和“50杯水”都含50，可以直接当同一种量比较吗？',
      [
        { id: 'different', label: '不能，先说明对象和单位' },
        { id: 'same', label: '可以，有50就是同一种量' },
      ],
      'different',
      '相同数字可以表示不同对象与单位，不把页、米、个、杯混同。',
    ),
    {
      id: `${id}-${review ? 'r' : 'q'}-tens`,
      knowledge: `${id}-tens`,
      prompt: review
        ? '把50张卡每10张一组，可分成几个完整组？'
        : '把50个同样物品每10个一组，可分成几个完整组？',
      rule: { kind: 'number', value: 5 },
      hint: '十个十个数到50，数完整组。',
      explanation: '5个十是50，不把组数5当总个数50。',
    },
  ];
}
