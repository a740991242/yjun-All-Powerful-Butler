import type { Lesson, Question } from '../learning/types';
const id = 'bnu-lower-count-hundred';
function task(
  suffix: string,
  prompt: string,
  rule: Question['rule'],
  explanation: string,
): Question {
  return {
    id: `${id}-${suffix}`,
    knowledge: id,
    prompt,
    rule,
    explanation,
    hint: '先分清根数与捆数，按要求把整段数完；真实摆捆、原图点数和交流另做。',
  };
}
const steps = (
  suffix: string,
  prompt: string,
  values: number[],
  explanation: string,
) => task(suffix, prompt, { kind: 'steps', values }, explanation);
const number = (
  suffix: string,
  prompt: string,
  value: number,
  explanation: string,
) => task(suffix, prompt, { kind: 'number', value }, explanation);
function choice(
  suffix: string,
  prompt: string,
  value: string,
  labels: string[],
  explanation: string,
): Question {
  return {
    ...task(suffix, prompt, { kind: 'choice', value }, explanation),
    choices: labels.map((label) => ({ id: label, label })),
  };
}
const actual = (suffix: string, prompt: string) =>
  task(
    suffix,
    prompt,
    { kind: 'manual' },
    '实际完整做过再确认，未做如实跳过；网页演示和答对不代替纸面、实物与交流。',
  );
const record = (suffix: string, prompt: string) =>
  task(
    suffix,
    prompt,
    { kind: 'reflection' },
    '保存自己的原话，不评分；已做、未做和未来计划分别记录。',
  );
