import type { Lesson, Question } from '../learning/types';

const id = 'bnu-lower-building-blocks';
function q(
  suffix: string,
  prompt: string,
  value: number,
  explanation: string,
): Question {
  return {
    id: `${id}-${suffix}`,
    knowledge: id,
    prompt,
    rule: { kind: 'number', value },
    hint: '先看原有、添上或拿走各多少；用个位算或逐个跳数，再核对总量与单位。',
    explanation,
  };
}
function manual(suffix: string, prompt: string): Question {
  return {
    ...q(
      suffix,
      prompt,
      0,
      '实际做过才确认；未做请跳过，网页计算不能证明实物、纸面或交流活动已完成。',
    ),
    rule: { kind: 'manual' },
  };
}

