import type { Lesson, Question } from '../learning/types';

const id = 'bnu-upper-final-number-talk';
function q(
  suffix: string,
  prompt: string,
  rule: Question['rule'],
  explanation: string,
  visual?: Question['visual'],
): Question {
  return {
    id: `${id}-${suffix}`,
    knowledge: id,
    prompt,
    rule,
    hint: '先说清所数对象与单位，严格多或少不含相等；两步变化从左往右。0是有效数量，未观察不当0。',
    explanation,
    ...(visual ? { visual } : {}),
  };
}
function choice(
  suffix: string,
  prompt: string,
  value: string,
  labels: string[],
  explanation: string,
): Question {
  return {
    ...q(suffix, prompt, { kind: 'choice', value }, explanation),
    choices: labels.map((label) => ({ id: label, label })),
  };
}
function actual(suffix: string, prompt: string): Question {
  return q(
    `actual-${suffix}`,
    `${prompt}；真实做过再确认，缺教材、材料或同伴可待做。`,
    { kind: 'manual' },
    '网页填数不代替实际作图、讲故事、观察或交流；计划另行记录。',
  );
}
