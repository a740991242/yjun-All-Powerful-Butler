import type { Lesson, Question } from '../learning/types';

const id = 'mu-five-methods';
function task(
  suffix: string,
  prompt: string,
  rule: Question['rule'],
  explanation: string,
  labels?: string[],
): Question {
  return {
    id: `${id}-${suffix}`,
    knowledge: id,
    prompt,
    rule,
    explanation,
    hint: '先看原有、变化或静态两部分，再看所求与单位；每条独立计算，指定方法要看实际数的起点，原书纸笔与口述另做。',
    choices: labels?.map((label) => ({ id: label, label })),
  };
}
function fields(
  suffix: string,
  prompt: string,
  values: number[],
  explanation: string,
) {
  return task(suffix, prompt, { kind: 'steps', values }, explanation);
}
function manual(suffix: string, prompt: string) {
  return task(
    suffix,
    prompt,
    { kind: 'manual' },
    '实际做完本项才确认，部分、替代、未做和未来计划如实记录，可跳过；网页答案不代替实际摆写说。',
  );
}
