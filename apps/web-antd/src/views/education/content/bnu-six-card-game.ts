import type { Lesson, Question } from '../learning/types';

const id = 'bnu-upper-six-card-game';
function q(
  suffix: string,
  prompt: string,
  rule: Question['rule'],
  explanation: string,
): Question {
  return {
    id: `${id}-${suffix}`,
    knowledge: id,
    prompt,
    rule,
    hint: '先看每张数卡和已摸张数，分清超过6、最多三张与最后合法结果。',
    explanation,
  };
}
function choice(
  suffix: string,
  prompt: string,
  value: string,
  labels: string[],
  explanation: string,
): Question {
  return {
    ...q(suffix, prompt, { kind: 'choice', value }, explanation),
    choices: labels.map((label) => ({ id: label, label })),
  };
}
function actual(suffix: string, prompt: string): Question {
  return q(
    `actual-${suffix}`,
    `${prompt}；真实做过再确认。`,
    { kind: 'manual' },
    '本站演示不冒真实轮流、隐藏牌、合作或原书已完成。',
  );
}
