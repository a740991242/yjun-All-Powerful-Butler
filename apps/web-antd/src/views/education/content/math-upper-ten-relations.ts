const id = 'mu-ten-relations';
function task(
  suffix: string,
  prompt: string,
  rule: Question['rule'],
  explanation: string,
  labels?: string[],
): Question {
  return {
    id: `${id}-${suffix}`,
    knowledge: id,
    prompt,
    rule,
    explanation,
    hint: '每条独立看自己的符号，轮盘每次都从中心数开始；相等部分不重复同式，等号两侧都要核对。',
    choices: labels?.map((label) => ({ id: label, label })),
  };
}
function fields(
  suffix: string,
  prompt: string,
  values: number[],
  explanation: string,
) {
  return task(suffix, prompt, { kind: 'steps', values }, explanation);
}
function manual(suffix: string, prompt: string) {
  return task(
    suffix,
    prompt,
    { kind: 'manual' },
    '实际完成本项才确认；没做、部分、替代和计划分开，可跳过。网页计算正确不当原图纸笔操作已完成。',
  );
}
const families = [6, 7, 8, 9, 10].flatMap((total) =>
  Array.from({ length: Math.floor(total / 2) }, (_, i) => {
    const a = i + 1;
    const b = total - a;
    const terms =
      a === b
        ? [`${a}+${b}`, `${total}−${a}`]
        : [`${a}+${b}`, `${b}+${a}`, `${total}−${a}`, `${total}−${b}`];
    const values = a === b ? [total, a] : [total, total, b, a];
    return fields(
      `family${total}-${a}`,
      `分合总${total}、两部分${a}/${b}，独立计算${terms.join('、')}，依给定顺序填结果。`,
      values,
      '交换两部分总量不变，总量减一个部分得另一个；相等部分只列一加一减，不重复同一式。',
    );
  }),
);
