import type { Lesson, Question } from '../learning/types';
const id = 'bnu-lower-complement-game';
function task(
  suffix: string,
  prompt: string,
  rule: Question['rule'],
  explanation: string,
): Question {
  return {
    id: `${id}-${suffix}`,
    knowledge: id,
    prompt,
    rule,
    explanation,
    hint: '先读目标与范围，再明确原数或减数的分解；固定不变与逐次变化的量分开。',
  };
}
function number(
  suffix: string,
  prompt: string,
  value: number,
  explanation: string,
) {
  return task(suffix, prompt, { kind: 'number', value }, explanation);
}
function steps(
  suffix: string,
  prompt: string,
  values: number[],
  explanation: string,
) {
  return task(suffix, prompt, { kind: 'steps', values }, explanation);
}
function pair(suffix: string, prompt: string, target: number) {
  return task(
    suffix,
    prompt,
    {
      kind: 'arithmetic-pair',
      minimum: 0,
      maximum: target,
      operation: 'add',
      result: target,
    },
    `本站两人有序填数均为0～${target}整数，两个数合${target}，全部合法组合都可；相同数可以来自两个人，0是本站明确补充。`,
  );
}
function choice(
  suffix: string,
  prompt: string,
  value: string,
  labels: string[],
  explanation: string,
): Question {
  return {
    ...task(suffix, prompt, { kind: 'choice', value }, explanation),
    choices: labels.map((label) => ({ id: label, label })),
  };
}
function actual(suffix: string, prompt: string) {
  return task(
    suffix,
    prompt,
    { kind: 'manual' },
    '实际做过再确认；原书核对、纸面游戏、书写和说明不由网页答对自动确认，未做如实跳过。',
  );
}
function record(suffix: string, prompt: string) {
  return task(
    suffix,
    prompt,
    { kind: 'reflection' },
    '自己的发现、困惑与未来计划原话保存，不评分，不冒已实际完成。',
  );
}
