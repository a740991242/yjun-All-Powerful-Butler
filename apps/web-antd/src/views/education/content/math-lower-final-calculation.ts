const id = 'ml-final-calculation';
function task(
  suffix: string,
  prompt: string,
  rule: Question['rule'],
  explanation: string,
  labels?: string[],
): Question {
  return {
    id: `${id}-${suffix}`,
    knowledge: id,
    prompt,
    rule,
    explanation,
    choices: labels?.map((label) => ({ id: label, label })),
    hint: '各独立式恢复原条件；链与连算从左向右保存每步。0要写出，空白不是0。',
  };
}
function fields(
  suffix: string,
  prompt: string,
  values: number[],
  explanation: string,
) {
  return task(suffix, prompt, { kind: 'steps', values }, explanation);
}
function manual(suffix: string, prompt: string) {
  return task(
    suffix,
    prompt,
    { kind: 'manual' },
    '实际完成指定全部计算、操作和说明才确认，只填网页或只做部分请跳过并记范围，计划另记。',
  );
}
