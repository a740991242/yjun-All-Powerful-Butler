const id = 'mu-five-organize';
function task(
  suffix: string,
  prompt: string,
  rule: Question['rule'],
  explanation: string,
  labels?: string[],
  visual?: Visual,
): Question {
  return {
    id: `${id}-${suffix}`,
    knowledge: id,
    prompt,
    rule,
    explanation,
    visual,
    hint: '先说范围、单位和已知条件，再摆或逐步数；每个部分只计一次，等号两边都要检查。',
    choices: labels?.map((label) => ({ id: label, label })),
  };
}
function fields(
  suffix: string,
  prompt: string,
  values: number[],
  explanation: string,
  visual?: Visual,
) {
  return task(
    suffix,
    prompt,
    { kind: 'steps', values },
    explanation,
    undefined,
    visual,
  );
}
function manual(suffix: string, prompt: string) {
  return task(
    suffix,
    prompt,
    { kind: 'manual' },
    '实际完成本项观察、摆画、书写或讲述才确认；没做或只做部分可跳过，原页与本站原创情境分开，不由网页正确推实做完成。',
  );
}
