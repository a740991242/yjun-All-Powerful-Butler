function task(
  id: string,
  suffix: string,
  prompt: string,
  rule: Question['rule'],
  hint: string,
  explanation: string,
  visual?: Visual,
  labels?: string[],
): Question {
  return {
    id: `${id}-${suffix}`,
    knowledge: id,
    prompt,
    rule,
    hint,
    explanation,
    visual,
    choices: labels?.map((label) => ({ id: label, label })),
  };
}
function manual(
  id: string,
  suffix: string,
  prompt: string,
  hint: string,
  visual?: Visual,
): Question {
  return task(
    id,
    suffix,
    prompt,
    { kind: 'manual' },
    hint,
    '只记录真实操作与表达，不自动评价作品或理解程度，不计客观正确率；未做可以跳过。',
    visual,
  );
}
function reflection(id: string, suffix: string, prompt: string): Question {
  return task(
    id,
    suffix,
    prompt,
    { kind: 'reflection' },
    '按实际经历写，未做或需要帮助也如实说明，可由家长代录。',
    '独立保存自己的观察和想法，没有统一正确答案，也不自动认定已掌握。',
  );
}
function choose(
  id: string,
  suffix: string,
  prompt: string,
  labels: string[],
  value: string,
  hint: string,
  explanation: string,
  visual?: Visual,
): Question {
  return task(
    id,
    suffix,
    prompt,
    { kind: 'choice', value },
    hint,
    explanation,
    visual,
    labels,
  );
}

