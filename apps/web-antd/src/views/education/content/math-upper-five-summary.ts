const id = 'mu-five-summary';
function task(
  suffix: string,
  prompt: string,
  rule: Question['rule'],
  explanation: string,
  labels?: string[],
): Question {
  return {
    id: `${id}-${suffix}`,
    knowledge: id,
    prompt,
    rule,
    explanation,
    hint: '每条算式独立看符号和条件；0不是空白，整理时所有合法算式都要有，开放比较先确定0～5的范围。',
    choices: labels?.map((label) => ({ id: label, label })),
  };
}
function fields(
  suffix: string,
  prompt: string,
  values: number[],
  explanation: string,
) {
  return task(suffix, prompt, { kind: 'steps', values }, explanation);
}
function manual(suffix: string, prompt: string) {
  return task(
    suffix,
    prompt,
    { kind: 'manual' },
    '实际完成本项纸卡、摆画、书写或讲述才确认；未做、部分、替代和计划分开，没做可跳过，网页答案不冒实做。',
  );
}
const additions = Array.from({ length: 6 }, (_, total) => {
  const terms = Array.from(
    { length: total + 1 },
    (_, second) => `${total - second}+${second}`,
  );
  return fields(
    `add${total}`,
    `和为${total}的完整一组：${terms.join('、')}。按给定顺序逐条填结果，每条独立。`,
    terms.map(() => total),
    '总量固定，两个加数交换或一增一减，和不变；0也在范围中。',
  );
});
const subtractions = Array.from({ length: 6 }, (_, original) => {
  const terms = Array.from(
    { length: original + 1 },
    (_, removed) => `${original}−${removed}`,
  );
  return fields(
    `sub${original}`,
    `原量${original}的完整一组：${terms.join('、')}。按给定顺序逐条填剩下数，不累计减去。`,
    terms.map((_, removed) => original - removed),
    '每条都从本组原量开始，去掉0不变，全部去掉剩0。',
  );
});
