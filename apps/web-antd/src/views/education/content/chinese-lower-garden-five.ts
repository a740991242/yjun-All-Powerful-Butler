function choice(
  key: string,
  prompt: string,
  labels: string[],
  value: string,
  explanation: string,
  review: boolean,
  material?: string,
): Question {
  return {
    id: `${id}-${review ? 'r' : 'q'}-${key}`,
    knowledge: `${id}-${key}`,
    prompt,
    material,
    choices: labels.map((label) => ({ id: label, label })),
    rule: { kind: 'choice', value },
    hint: '先看本题限定字词和原书信息，家长可以帮读。',
    explanation,
  };
}
function objective(review: boolean): Question[] {
  return [
    ...recognition.map(([c, main, next], i) =>
      choice(
        `char-${i}`,
        review ? next : main,
        recognition.map((r) => r[0]),
        c,
        '按指定词认字，实际读音需另行确认，会认与会写清单分开。',
        review,
      ),
    ),
    ...pairs.map((p) =>
      choice(
        p.key,
        p.prompts[review ? 1 : 0],
        p.labels,
        p.values[review ? 1 : 0],
        p.explanation,
        review,
        p.material,
      ),
    ),
  ];
}
