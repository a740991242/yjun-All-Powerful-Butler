import type { Lesson, Question } from '../learning/types';
const id = 'bnu-lower-hide-and-seek';
function task(
  suffix: string,
  prompt: string,
  rule: Question['rule'],
  explanation: string,
): Question {
  return {
    id: `${id}-${suffix}`,
    knowledge: id,
    prompt,
    rule,
    explanation,
    hint: '先明确参与范围和所求，再按指定方法检查退位与每一步；珠子颗数不等于表示的数。',
  };
}
function number(
  suffix: string,
  prompt: string,
  value: number,
  explanation: string,
) {
  return task(suffix, prompt, { kind: 'number', value }, explanation);
}
function steps(
  suffix: string,
  prompt: string,
  values: number[],
  explanation: string,
) {
  return task(suffix, prompt, { kind: 'steps', values }, explanation);
}
function choice(
  suffix: string,
  prompt: string,
  value: string,
  labels: string[],
  explanation: string,
): Question {
  return {
    ...task(suffix, prompt, { kind: 'choice', value }, explanation),
    choices: labels.map((label) => ({ id: label, label })),
  };
}
function actual(suffix: string, prompt: string) {
  return task(
    suffix,
    prompt,
    { kind: 'manual' },
    '实际做过再确认；纸面替代说明材料，未做如实跳过，网页结果不确认实物操作。',
  );
}
function record(suffix: string, prompt: string) {
  return task(
    suffix,
    prompt,
    { kind: 'reflection' },
    '原话保存且不评分，真实活动、自己的理解与未来计划分开。',
  );
}
