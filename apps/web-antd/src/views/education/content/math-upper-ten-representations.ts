import type { Lesson, Question, Visual } from '../learning/types';

const id = 'mu-ten-representations';
function task(
  suffix: string,
  prompt: string,
  rule: Question['rule'],
  explanation: string,
  visual?: Visual,
  labels?: string[],
): Question {
  return {
    id: `${id}-${suffix}`,
    knowledge: id,
    prompt,
    rule,
    explanation,
    visual,
    hint: '先确定同一类对象再逐一点数；格位不是物体，空白不是已涂点。数字结果、网页点格、原书纸面与真实拨珠分别记录。',
    choices: labels?.map((label) => ({ id: label, label })),
  };
}
function fields(
  suffix: string,
  prompt: string,
  values: number[],
  explanation: string,
  visual?: Visual,
) {
  return task(suffix, prompt, { kind: 'steps', values }, explanation, visual);
}
function manual(suffix: string, prompt: string) {
  return task(
    suffix,
    prompt,
    { kind: 'manual' },
    '实际做完才确认，未做、部分、替代、帮助和计划分别如实记录，可跳过；屏幕答案不冒原图/纸面/实物已做。',
  );
}
