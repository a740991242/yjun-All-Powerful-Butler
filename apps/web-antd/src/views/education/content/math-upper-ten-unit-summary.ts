import type { Lesson, Question } from '../learning/types';

const id = 'mu-ten-unit-summary';
function task(
  suffix: string,
  prompt: string,
  rule: Question['rule'],
  explanation: string,
  labels?: string[],
): Question {
  return {
    id: `${id}-${suffix}`,
    knowledge: id,
    prompt,
    rule,
    explanation,
    hint: '先读条件、单位和所求；整数范围与最小条件分别满足，每条独立算并保留中间量，自主提问和实做另记录。',
    choices: labels?.map((label) => ({ id: label, label })),
  };
}
function fields(
  suffix: string,
  prompt: string,
  values: number[],
  explanation: string,
) {
  return task(suffix, prompt, { kind: 'steps', values }, explanation);
}
function manual(suffix: string, prompt: string) {
  return task(
    suffix,
    prompt,
    { kind: 'manual' },
    '实际做完本项才确认，没做、部分、替代与计划分别如实记录，可跳过；网页算对不冒原书纸笔或交流已完成。',
  );
}
