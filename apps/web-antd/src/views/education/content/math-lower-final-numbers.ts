const id = 'ml-final-numbers';
const range = (start: number, end: number) =>
  Array.from({ length: end - start + 1 }, (_, i) => start + i);
function task(
  suffix: string,
  prompt: string,
  rule: Question['rule'],
  explanation: string,
  labels?: string[],
): Question {
  return {
    id: `${id}-${suffix}`,
    knowledge: id,
    prompt,
    rule,
    explanation,
    choices: labels?.map((label) => ({ id: label, label })),
    hint: '先看数表起点、行列与从哪边数；横邻与数的相邻不同，0不是空白。',
  };
}
function manual(suffix: string, prompt: string) {
  return task(
    suffix,
    prompt,
    { kind: 'manual' },
    '实际完成指定全部操作与解释才确认；仅看网页、计划做或缺教材请跳过，如实记范围。',
  );
}
