function task(
  suffix: string,
  prompt: string,
  rule: Question['rule'],
  explanation: string,
  labels?: string[],
  visual?: Visual,
): Question {
  return {
    id: `${id}-${suffix}`,
    knowledge: id,
    prompt,
    rule,
    explanation,
    visual,
    hint: '先说谁的方向、朝向哪里、从哪里起数；数量与位置、编号分开。',
    choices: labels?.map((label) => ({ id: label, label })),
  };
}
function fields(
  suffix: string,
  prompt: string,
  values: number[],
  explanation: string,
  visual?: Visual,
) {
  return task(
    suffix,
    prompt,
    { kind: 'steps', values },
    explanation,
    undefined,
    visual,
  );
}
function manual(suffix: string, prompt: string, visual?: Visual) {
  return task(
    suffix,
    prompt,
    { kind: 'manual' },
    '只有实际完成指定观察、纸面摆放或交流并记录才确认；看网页不替实际活动，未知信息如实记，没做或只做部分可跳过。',
    undefined,
    visual,
  );
}
