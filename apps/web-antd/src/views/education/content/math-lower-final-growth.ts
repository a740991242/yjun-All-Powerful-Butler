import type { Lesson, Question } from '../learning/types';
const id = 'ml-final-growth';
function task(
  suffix: string,
  prompt: string,
  rule: Question['rule'],
  explanation: string,
  labels?: string[],
): Question {
  return {
    id: `${id}-${suffix}`,
    knowledge: id,
    prompt,
    rule,
    explanation,
    hint: '实际做过、仍不确定和未来计划分开；可以如实说没有经历，不要求每方面都表现好。',
    choices: labels?.map((label) => ({ id: label, label })),
  };
}
function manual(suffix: string, prompt: string) {
  return task(
    suffix,
    prompt,
    { kind: 'manual' },
    '确认表示实际完成了如实回顾或指定整理，不表示已具备能力；没回顾、没操作或只是计划请跳过。',
  );
}
function reflection(suffix: string, prompt: string) {
  return task(
    suffix,
    prompt,
    { kind: 'reflection' },
    '独立开放反思，correct:null；不按词语、积极程度、字数或成绩自动评星。',
  );
}
