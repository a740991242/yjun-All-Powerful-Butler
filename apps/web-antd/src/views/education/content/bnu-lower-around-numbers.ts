import type { Lesson, Question } from '../learning/types';

const id = 'bnu-lower-around-numbers';
function task(
  suffix: string,
  prompt: string,
  rule: Question['rule'],
  explanation: string,
): Question {
  return {
    id: `${id}-${suffix}`,
    knowledge: id,
    prompt,
    rule,
    explanation,
    hint: '先说每个标记代表几个，再逐个核对；实际数数、作图和调查不能由网页答案代替。',
  };
}
const steps = (
  suffix: string,
  prompt: string,
  values: number[],
  explanation: string,
) => task(suffix, prompt, { kind: 'steps', values }, explanation);
const number = (
  suffix: string,
  prompt: string,
  value: number,
  explanation: string,
) => task(suffix, prompt, { kind: 'number', value }, explanation);
function choice(
  suffix: string,
  prompt: string,
  value: string,
  labels: string[],
  explanation: string,
): Question {
  return {
    ...task(suffix, prompt, { kind: 'choice', value }, explanation),
    choices: labels.map((label) => ({ id: label, label })),
  };
}
const actual = (suffix: string, prompt: string) =>
  task(
    suffix,
    prompt,
    { kind: 'manual' },
    '实际完整做过再确认；尚未做可跳过。网页答对不自动确认数原图、摆画、说数或调查。',
  );
const record = (suffix: string, prompt: string) =>
  task(
    suffix,
    prompt,
    { kind: 'reflection' },
    '按真实情况保留原话，不评分。已完成、尚未做和未来计划分别记录。',
  );
