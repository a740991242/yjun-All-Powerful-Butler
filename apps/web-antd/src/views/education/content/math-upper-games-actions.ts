import type { Lesson, Question, Visual } from '../learning/types';

const id = 'mu-games-actions';
function task(
  suffix: string,
  prompt: string,
  rule: Question['rule'],
  explanation: string,
  labels?: string[],
  visual?: Visual,
): Question {
  return {
    id: `${id}-${suffix}`,
    knowledge: id,
    prompt,
    rule,
    explanation,
    hint: '先读本轮规则，再说计数范围、起点和单位；自己的左右不换成对面人的左右。',
    choices: labels?.map((label) => ({ id: label, label })),
    visual,
  };
}
function fields(
  suffix: string,
  prompt: string,
  values: number[],
  explanation: string,
  visual?: Visual,
) {
  return task(
    suffix,
    prompt,
    { kind: 'steps', values },
    explanation,
    undefined,
    visual,
  );
}
function manual(suffix: string, prompt: string, visual?: Visual) {
  return task(
    suffix,
    prompt,
    { kind: 'manual' },
    '只有实际做完该项并记录才确认。可用纸卡、指点或辅助沟通替代并说明；没做、只做部分或只计划可跳过，不从网页作答推真实活动已完成。',
    undefined,
    visual,
  );
}
