import type { Lesson, Question } from '../learning/types';
const id = 'bnu-lower-meeting';
function task(
  suffix: string,
  prompt: string,
  rule: Question['rule'],
  explanation: string,
): Question {
  return {
    id: `${id}-${suffix}`,
    knowledge: id,
    prompt,
    rule,
    explanation,
    hint: '先明确每人或每只需要一件，再分清已有、总需与还缺；画图逐个配对，说明单位。',
  };
}
function number(
  suffix: string,
  prompt: string,
  value: number,
  explanation: string,
) {
  return task(suffix, prompt, { kind: 'number', value }, explanation);
}
function steps(
  suffix: string,
  prompt: string,
  values: number[],
  explanation: string,
) {
  return task(suffix, prompt, { kind: 'steps', values }, explanation);
}
function choice(
  suffix: string,
  prompt: string,
  value: string,
  labels: string[],
  explanation: string,
): Question {
  return {
    ...task(suffix, prompt, { kind: 'choice', value }, explanation),
    choices: labels.map((label) => ({ id: label, label })),
  };
}
function actual(suffix: string, prompt: string) {
  return task(
    suffix,
    prompt,
    { kind: 'manual' },
    '实际做过再确认；原书核对、纸面游戏、书写和说明不由网页答对自动确认，未做如实跳过。',
  );
}
function record(suffix: string, prompt: string) {
  return task(
    suffix,
    prompt,
    { kind: 'reflection' },
    '自己的发现、困惑与未来计划原话保存，不评分，不冒已实际完成。',
  );
}
