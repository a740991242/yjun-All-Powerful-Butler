function pair(
  key: string,
  prompts: [string, string],
  values: [string, string],
  wrong: string,
  explanation: string,
  material = '先与家长共读对应原书页，再按本题限定段落和信息观察。',
): Pair {
  return {
    key,
    prompts,
    values,
    labels: [...new Set([...values, wrong])],
    explanation,
    material,
  };
}
function chars(
  characters: string,
): NonNullable<Lesson['steps'][number]['visual']> {
  return { kind: 'characters', grid: 'tian', characters: [...characters] };
}
