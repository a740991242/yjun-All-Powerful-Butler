function task(
  suffix: string,
  prompt: string,
  rule: Question['rule'],
  explanation: string,
  labels?: string[],
  visual?: Visual,
): Question {
  return {
    id: `${id}-${suffix}`,
    knowledge: id,
    prompt,
    rule,
    explanation,
    visual,
    hint: '先说数的对象、起点和已知范围；前后不含本人，遮挡的数量需要条件，多个合法答案都检查。',
    choices: labels?.map((label) => ({ id: label, label })),
  };
}
function fields(
  suffix: string,
  prompt: string,
  values: number[],
  explanation: string,
  visual?: Visual,
) {
  return task(
    suffix,
    prompt,
    { kind: 'steps', values },
    explanation,
    undefined,
    visual,
  );
}
function manual(suffix: string, prompt: string) {
  return task(
    suffix,
    prompt,
    { kind: 'manual' },
    '实际完成本项摆画、书写、观察或讲述才确认；没做、只做部分或缺原页可跳过。本站原创与原图分记，网页判题不替代实际活动。',
  );
}

