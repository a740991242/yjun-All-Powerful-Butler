const id = 'ml-oral-groups';
function task(
  suffix: string,
  prompt: string,
  rule: Question['rule'],
  explanation: string,
  labels?: string[],
  visual?: Visual,
): Question {
  return {
    id: `${id}-${suffix}`,
    knowledge: id,
    prompt,
    rule,
    explanation,
    choices: labels?.map((label) => ({ id: label, label })),
    visual,
    hint: '先说求满组、剩余还是装完全部；每一步从剩余量继续，不够一组时停止。0要实际填，未知不是0。',
  };
}
