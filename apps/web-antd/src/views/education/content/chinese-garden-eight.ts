function choice(
  key: string,
  prompt: string,
  labels: string[],
  value: string,
  explanation: string,
  review: boolean,
  material?: string,
): Question {
  return {
    id: `${id}-${review ? 'r' : 'q'}-${key}`,
    knowledge: `${id}-${key}`,
    prompt,
    material,
    choices: labels.map((label) => ({ id: label, label })),
    rule: { kind: 'choice', value },
    hint: '先看指定字词与原书信息，开放表达不用唯一答案。',
    explanation,
  };
}
function objective(review: boolean): Question[] {
  const i = review ? 1 : 0;
  return [
    ...characters.map((r, n) =>
      choice(
        `char-${n}`,
        required(r[i + 1]),
        characters.map((c) => required(c[0])),
        required(r[0]),
        '新增认牛羊爪元拼音，写牛羊爪白，其他活动字另看。',
        review,
      ),
    ),
    ...gardenEightStructures.map(([char, structure, other], n) =>
      choice(
        `structure-${n}`,
        review
          ? `按第101页连线观察，只比较${char}与${other}，哪项归${structure}组？`
          : `按第101页结构分类，${char}属于哪项？`,
        review ? [char, other] : ['上下', '独体', '左右'],
        review ? char : structure,
        '按本页连线观察：原页示例元连花、巴连田、叶连作。元按本页上下两部分示范，不把这个观察分组当所有字典结构术语；羊按整体看，不能只数横线或笔画。',
        review,
      ),
    ),
    ...gardenEightWordPairs.map(([a, b, av, bv], n) =>
      choice(
        `word-${n}`,
        `第101页${review ? b : a}中${(() => {
          if (n === 2) return '第二';
          return n === 5 && !review ? '第二' : '第一';
        })()}个字是哪项？`,
        [av, bv, '本题没有这个字'],
        review ? bv : av,
        '按指定词的位置找字，十二词实际朗读另行确认，不扩新增认写范围。',
        review,
      ),
    ),
    ...pairs.map((p) =>
      choice(
        p.key,
        p.prompts[i],
        p.labels,
        p.values[i],
        p.explanation,
        review,
        p.material,
      ),
    ),
  ];
}
function manual(key: string, prompt: string, material?: string): Question {
  return {
    id: `${id}-manual-${key}`,
    knowledge: `${id}-manual-${key}`,
    prompt,
    material,
    rule: { kind: 'manual' },
    hint: '实际尝试后家长确认，缺书、示范或纸笔可跳过。',
    explanation: '不自动评声音笔顺表达，未来计划不当完成。',
  };
}
