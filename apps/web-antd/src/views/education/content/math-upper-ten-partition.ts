import type { Lesson, Question } from '../learning/types';

const id = 'mu-ten-full-partition';
function task(
  suffix: string,
  prompt: string,
  rule: Question['rule'],
  explanation: string,
  labels?: string[],
): Question {
  return {
    id: `${id}-${suffix}`,
    knowledge: id,
    prompt,
    rule,
    explanation,
    hint: '先看总量、部分和起点；两组都非空，实体卡每张最多取一次；中间数也要填，未知不是0。',
    choices: labels?.map((label) => ({ id: label, label })),
  };
}
function fields(
  suffix: string,
  prompt: string,
  values: number[],
  explanation: string,
) {
  return task(suffix, prompt, { kind: 'steps', values }, explanation);
}
function set(
  suffix: string,
  prompt: string,
  values: string[],
  labels: string[],
  explanation: string,
) {
  return task(suffix, prompt, { kind: 'set', values }, explanation, labels);
}
function manual(suffix: string, prompt: string) {
  return task(
    suffix,
    prompt,
    { kind: 'manual' },
    '实际做完本项才确认；没做、部分、替代与计划如实分开，可跳过。网页算对不代表完成原页活动。',
  );
}
function orderedPairs(n: number) {
  return Array.from({ length: n - 1 }, (_, i) => `${i + 1}和${n - i - 1}`);
}
