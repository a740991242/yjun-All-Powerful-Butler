import type { ClockVisual, Lesson, Question } from '../learning/types';

const id = 'bnu-upper-day-record';
const clock = (hour: number, minute: 0 | 30): ClockVisual => ({
  kind: 'clock',
  hour,
  minute,
});
function q(
  suffix: string,
  prompt: string,
  rule: Question['rule'],
  explanation: string,
  visual?: Question['visual'],
): Question {
  return {
    id: `${id}-${suffix}`,
    knowledge: id,
    prompt,
    rule,
    explanation,
    hint: '按当前图中完整物件与层次核对，分清时针、分针、整时、半时与一天中的情境，不用他人作息代替自己。',
    ...(visual ? { visual } : {}),
  };
}
function choice(
  suffix: string,
  prompt: string,
  value: string,
  labels: string[],
  explanation: string,
  visual?: Question['visual'],
): Question {
  return {
    ...q(suffix, prompt, { kind: 'choice', value }, explanation, visual),
    choices: labels.map((label) => ({ id: label, label })),
  };
}
function actual(suffix: string, prompt: string): Question {
  return q(
    `actual-${suffix}`,
    `${prompt}；真实做过再确认，没有钟面、同伴或未看原书可待做。`,
    { kind: 'manual' },
    '网页答案不代替拨画钟面、实际记录、分享或倾听；未来计划与真实活动分开。',
  );
}
