import type { Lesson, Question } from '../learning/types';

const id = 'bnu-lower-unit-one-harvest';
function task(
  suffix: string,
  prompt: string,
  rule: Question['rule'],
  explanation: string,
): Question {
  return {
    id: `${id}-${suffix}`,
    knowledge: id,
    prompt,
    rule,
    hint: '先确认数的对象与单位。凑十的两种路径分别核对；换捆或换珠不改变所表示的数。',
    explanation,
  };
}
function number(
  suffix: string,
  prompt: string,
  value: number,
  explanation: string,
) {
  return task(suffix, prompt, { kind: 'number', value }, explanation);
}
function actual(suffix: string, prompt: string) {
  return task(
    suffix,
    prompt,
    { kind: 'manual' },
    '实际摆、拨、画或说过再确认；只看网页或有未来计划请跳过，客观答对不能代替实际活动。',
  );
}

