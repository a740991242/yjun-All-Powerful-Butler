import type { Lesson, Question } from '../learning/types';

const id = 'bnu-lower-countryside';
function task(
  suffix: string,
  prompt: string,
  rule: Question['rule'],
  explanation: string,
): Question {
  return {
    id: `${id}-${suffix}`,
    knowledge: id,
    prompt,
    rule,
    explanation,
    hint: '先分清正在数哪一组、已知和所求；逐对象点数，再画图列式，说出单位。',
  };
}
const number = (
  suffix: string,
  prompt: string,
  value: number,
  explanation: string,
) => task(suffix, prompt, { kind: 'number', value }, explanation);
const steps = (
  suffix: string,
  prompt: string,
  values: number[],
  explanation: string,
) => task(suffix, prompt, { kind: 'steps', values }, explanation);
function choice(
  suffix: string,
  prompt: string,
  value: string,
  labels: string[],
  explanation: string,
): Question {
  return {
    ...task(suffix, prompt, { kind: 'choice', value }, explanation),
    choices: labels.map((label) => ({ id: label, label })),
  };
}
const actual = (suffix: string, prompt: string) =>
  task(
    suffix,
    prompt,
    { kind: 'manual' },
    '实际点数、画写或说过再确认；未做如实跳过，网页正确不自动确认真实活动。',
  );
const record = (suffix: string, prompt: string) =>
  task(
    suffix,
    prompt,
    { kind: 'reflection' },
    '自己的原话保存，不评分；待做和未来计划不当已经完成。',
  );

