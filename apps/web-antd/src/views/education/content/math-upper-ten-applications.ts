import type { Lesson, Question } from '../learning/types';

const id = 'mu-ten-applications';
function task(
  suffix: string,
  prompt: string,
  rule: Question['rule'],
  explanation: string,
  labels?: string[],
): Question {
  return {
    id: `${id}-${suffix}`,
    knowledge: id,
    prompt,
    rule,
    explanation,
    hint: '先找同一所求的条件与单位，再按时间顺序算；先后两步要填中间量，未知与0不同。',
    choices: labels?.map((label) => ({ id: label, label })),
  };
}
function fields(
  suffix: string,
  prompt: string,
  values: number[],
  explanation: string,
) {
  return task(suffix, prompt, { kind: 'steps', values }, explanation);
}
function manual(suffix: string, prompt: string) {
  return task(
    suffix,
    prompt,
    { kind: 'manual' },
    '实际完成本项才确认；没做、部分、替代和计划分开，可跳过。网页计算正确不当原图纸笔操作已完成。',
  );
}
