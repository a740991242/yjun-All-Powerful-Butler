const id = 'sj-upper-ten-evaluation';
function tasks(review: boolean): Question[] {
  const q = (
    key: string,
    prompt: string,
    rule: Question['rule'],
    explanation: string,
  ): Question => ({
    id: `${id}-${review ? 'r' : 'q'}-${key}`,
    knowledge: `${id}-${key}`,
    prompt,
    rule,
    hint: '读清总数、一部分、要找的量和填写顺序；实做与反思分开记录。',
    explanation,
  });
  return [
    q(
      'ten-places',
      review
        ? '数字10，依次填个位有几个一、十位有几个十。先个位再十位。'
        : '数字10，依次填十位有几个十、个位有几个一。先十位再个位。',
      { kind: 'steps', values: review ? [0, 1] : [1, 0] },
      '10是一个十、零个一。填写次序改变但数量关系不变，0不是未填。',
    ),
    q(
      'sum-ten',
      review
        ? '依次填1+□=10、4+□=10、0+□=10、5+□=10中的另一个加数。'
        : '依次填1+9、4+6、0+10、5+5的和。',
      { kind: 'steps', values: review ? [9, 6, 10, 5] : [10, 10, 10, 10] },
      '分合关系检查两部分和为10；复习求缺少部分，不能复制原和。',
    ),
    q(
      'ten-subtract',
      review
        ? '依次填10−2、10−3、10−9、10−10的差。'
        : '依次填10−1、10−4、10−10、10−5的差。',
      { kind: 'steps', values: review ? [8, 7, 1, 0] : [9, 6, 0, 5] },
      '从总数10拿走已知数；拿走全部差0，明确写0。',
    ),
    q(
      'join-story',
      review
        ? '桌上有3本书，又放来6本。现在一共有多少本？填数，单位是本。'
        : '桌上有6支铅笔，又放来4支。现在一共有多少支？填数，单位是支。',
      { kind: 'number', value: review ? 9 : 10 },
      review
        ? '3+6=9，本题总数是9，不因本课讲10就写10。'
        : '6+4=10，把原有和又来合并。',
    ),
    q(
      'other-story',
      review
        ? '一共有9颗珠，其中4颗在袋外，剩余在袋内。袋内有多少颗？'
        : '一共有10颗珠，其中3颗在袋外，剩余在袋内。袋内有多少颗？',
      { kind: 'number', value: review ? 5 : 7 },
      review ? '9−4=5颗，9是总数。' : '10−3=7颗，总数减去已知一部分。',
    ),
    {
      ...q(
        'care-evidence',
        review
          ? '第一次写错，后来重新摆物和检查找到了原因。这能作为认真思考的真实证据吗？'
          : '认真思考的评价该根据什么？',
        { kind: 'choice', value: 'actual' },
        '认真思考看真实读题、操作、检查、求助和改正；出错不等于没有认真，也不自动给星。',
      ),
      choices: review
        ? [
            { id: 'actual', label: '能，如实记错误、检查和改正' },
            { id: 'auto', label: '不能，只有从不出错才算认真' },
          ]
        : [
            { id: 'actual', label: '真实怎样读题、操作和核对' },
            { id: 'auto', label: '网页答对自动给满星' },
          ],
    },
  ];
}
