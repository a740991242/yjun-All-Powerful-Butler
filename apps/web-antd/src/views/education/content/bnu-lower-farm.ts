import type { Lesson, Question } from '../learning/types';

const id = 'bnu-lower-happy-farm';
function q(
  suffix: string,
  prompt: string,
  rule: Question['rule'],
  explanation: string,
): Question {
  return {
    id: `${id}-${suffix}`,
    knowledge: id,
    prompt,
    rule,
    hint: '先说哪一部分凑成10，再说另一数分出了多少、还剩多少；各空按题目顺序记录。',
    explanation,
  };
}
function number(
  suffix: string,
  prompt: string,
  value: number,
  explanation: string,
): Question {
  return q(suffix, prompt, { kind: 'number', value }, explanation);
}
function method(
  suffix: string,
  prompt: string,
  values: number[],
  explanation: string,
): Question {
  return q(suffix, prompt, { kind: 'steps', values }, explanation);
}
function actual(suffix: string, prompt: string): Question {
  return q(
    suffix,
    prompt,
    { kind: 'manual' },
    '实际读图、摆棒、圈记或交流后才确认；未做请跳过，网页填数不能代替纸面操作。',
  );
}

