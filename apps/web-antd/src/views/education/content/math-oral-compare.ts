import type { Lesson, Question } from '../learning/types';

const id = 'ml-oral-compare';
function task(
  suffix: string,
  prompt: string,
  rule: Question['rule'],
  explanation: string,
  labels?: string[],
): Question {
  return {
    id: `${id}-${suffix}`,
    knowledge: id,
    prompt,
    rule,
    explanation,
    hint: '先说已知和所求、几个一或几个十；两步按时刻记录，0不是空白。纸面先判断再算，网页核对不替实际操作。',
    choices: labels?.map((label) => ({ id: label, label })),
  };
}
function manual(suffix: string, prompt: string) {
  return task(
    suffix,
    prompt,
    { kind: 'manual' },
    '实际读题、摆画、写步骤或解释后才确认；只准备、看示例或未做请跳过，未来计划另记。',
  );
}
