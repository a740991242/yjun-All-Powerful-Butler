const id = 'ml-final-applications';
function task(
  suffix: string,
  prompt: string,
  rule: Question['rule'],
  explanation: string,
  labels?: string[],
): Question {
  return {
    id: `${id}-${suffix}`,
    knowledge: id,
    prompt,
    rule,
    explanation,
    hint: '先明确已知、所求和单位；每题恢复自己的原条件。装满盒数、余数与全部需要盒数分开。',
    choices: labels?.map((label) => ({ id: label, label })),
  };
}
function fields(
  suffix: string,
  prompt: string,
  values: number[],
  explanation: string,
) {
  return task(suffix, prompt, { kind: 'steps', values }, explanation);
}
function manual(suffix: string, prompt: string) {
  return task(
    suffix,
    prompt,
    { kind: 'manual' },
    '实际完成指定全部任务和说明才确认；缺材料、只完成部分或未来计划请跳过并如实记录。',
  );
}
