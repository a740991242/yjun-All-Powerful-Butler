import type { Lesson, Question } from '../learning/types';

const id = 'ml-oral-organize';
function task(
  suffix: string,
  prompt: string,
  rule: Question['rule'],
  explanation: string,
  labels?: string[],
): Question {
  return {
    id: `${id}-${suffix}`,
    knowledge: id,
    prompt,
    rule,
    explanation,
    choices: labels?.map((label) => ({ id: label, label })),
    hint: '每式回自己的原条件；先检查本来是否正确，比较不漏等于，开放空接受所有明确范围内的合法数。0不是空白。',
  };
}
function manual(suffix: string, prompt: string) {
  return task(
    suffix,
    prompt,
    { kind: 'manual' },
    '实际完成全部指定操作、计算与解释才确认；原书缺材料或只准备请跳过，未来计划另记。',
  );
}
