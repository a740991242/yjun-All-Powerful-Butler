const id = 'ml-hundred-finish';
function task(
  suffix: string,
  prompt: string,
  rule: Question['rule'],
  explanation: string,
  labels?: string[],
  visual?: Visual,
): Question {
  return {
    id: `${id}-${suffix}`,
    knowledge: id,
    prompt,
    rule,
    explanation,
    hint: '先核对路径或数卡的条件，逐项记清；0是数，不是空白。',
    choices: labels?.map((label) => ({ id: label, label })),
    visual,
  };
}
