function task(
  id: string,
  suffix: string,
  prompt: string,
  rule: Question['rule'],
  explanation: string,
  visual?: Visual,
  labels?: string[],
): Question {
  return {
    id: `${id}-${suffix}`,
    knowledge: id,
    prompt,
    rule,
    visual,
    choices: labels?.map((label) => ({ id: label, label })),
    hint: '先确认每个一、十和百的意义，按指定字段填写；0不是空白。',
    explanation,
  };
}
function fields(
  id: string,
  suffix: string,
  prompt: string,
  values: number[],
  explanation: string,
  visual?: Visual,
) {
  return task(
    id,
    suffix,
    prompt,
    { kind: 'steps', values },
    explanation,
    visual,
  );
}
function number(
  id: string,
  suffix: string,
  prompt: string,
  value: number,
  explanation: string,
  visual?: Visual,
) {
  return task(
    id,
    suffix,
    prompt,
    { kind: 'number', value },
    explanation,
    visual,
  );
}
function choice(
  id: string,
  suffix: string,
  prompt: string,
  labels: string[],
  value: string,
  explanation: string,
) {
  return task(
    id,
    suffix,
    prompt,
    { kind: 'choice', value },
    explanation,
    undefined,
    labels,
  );
}
function set(
  id: string,
  suffix: string,
  prompt: string,
  labels: string[],
  values: string[],
  explanation: string,
) {
  return task(
    id,
    suffix,
    prompt,
    { kind: 'set', values },
    explanation,
    undefined,
    labels,
  );
}
function manual(id: string, suffix: string, prompt: string, visual?: Visual) {
  return task(
    id,
    suffix,
    prompt,
    { kind: 'manual' },
    '只记录是否实际完成，不自动评判实际点数、书写、摆放、读音或交流质量；未做、只准备或缺材料请跳过，计划另记。',
    visual,
  );
}
function reflect(id: string, suffix: string, prompt: string) {
  return task(
    id,
    suffix,
    prompt,
    { kind: 'reflection' },
    '如实记录已做与待做，反思没有统一正确答案，不计客观正确率。',
  );
}
